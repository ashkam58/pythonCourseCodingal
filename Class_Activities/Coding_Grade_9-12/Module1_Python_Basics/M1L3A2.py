# Activity 2: Checking conditions using logic and comparison

number = 24

if number % 2 == 0:
    print(number, "is an Even number.")
else:
    print(number, "is an Odd number.")

# Logical Operators (AND, OR, NOT)
a = 15
print("a > 10 and a < 20:", a > 10 and a < 20)
print("a < 10 or a > 12:", a < 10 or a > 12)
print("not(a > 10):", not(a > 10))
