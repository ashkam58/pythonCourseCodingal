# M3L6A1: Lists Basics
# Activity 1: Creating, Repeating, and Reversing Lists in Python

# Create an empty list
empty_list = []
print("Empty List:", empty_list)
print()

# A list of numbers
numbers = [1, 2, 3, 4, 5]
print("Numbers List:", numbers)

# Use * operator
triples = [1, 2, 3] * 3
print("Triples List (* operator):", triples)

# Reverse the given list
aList = [100, 200, 300, 400, 500]
aList = aList[::-1]
print("Reversed List:", aList, "\n")
